import { trace, unloads } from "./index.safe";

import { ContextMenu, Playlist, type MediaItem } from "@luna/lib";

import { getMaxItemQuiet } from ".";

const maxButton = ContextMenu.addButton(unloads);
let creating = false;

ContextMenu.onMediaItem(unloads, async ({ mediaCollection, contextMenu }) => {
	const itemCount = await mediaCollection.count();
	if (itemCount === 0) return;

	const defaultText = (maxButton.text = `RealMAX ${itemCount} tracks`);

	maxButton.onClick(async () => {
		// One playlist at a time, a second click would create a duplicate
		if (creating) return;
		creating = true;
		const mediaItems: MediaItem[] = [];
		let sourceTitle: string | undefined;
		maxButton.text = `RealMAX Loading...`;

		try {
			sourceTitle = await mediaCollection.title();
			let replacements = 0;
			// count() is the number of tracks (videos not included), so the progress counts tracks only
			let tracksDone = 0;
			for await (const mediaItem of await mediaCollection.mediaItems()) {
				if (mediaItem.contentType === "track") tracksDone++;
				// A failed lookup keeps the track as it is instead of failing the whole playlist
				const maxItem = await getMaxItemQuiet(mediaItem).catch(trace.err.withContext("getMaxItemQuiet", mediaItem.id));
				if (!maxItem) mediaItems.push(mediaItem);
				else {
					mediaItems.push(maxItem);
					replacements++;
				}
				maxButton.text = `RealMAX ${tracksDone}/${itemCount} done. Found ${replacements} replacements`;
			}

			if (replacements === 0) return trace.msg.err(`No replacements found for ${sourceTitle}`);

			maxButton.text = `RealMAX Creating playlist...`;
			await Playlist.create(`[RealMAX] ${sourceTitle}`, { description: "Automatically generated by RealMAX", mediaItems });
			trace.msg.log(`Created playlist "${sourceTitle}" with ${replacements} replacements!`);
		} catch (err) {
			trace.msg.err.withContext(`Failed to create playlist "${sourceTitle}"`)(err);
		} finally {
			creating = false;
			maxButton.text = defaultText;
		}
	});

	await maxButton.show(contextMenu);
});
